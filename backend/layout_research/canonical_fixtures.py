def _apply_row_label_contract(spec: CanonicalFixtureSpec) -> CanonicalFixtureSpec:
    """Contract decision (declared once, applied to every fixture).

    A header cell in the row-label column is the COLUMN_HEADER_OF parent
    of every row-header cell below it in that column: the label header
    governs the whole row-header column, and each row-header cell carries
    COLUMN context pointing at it.
    """
    grid = {(cell.row, cell.col): cell for cell in spec.cells}
    direct = list(spec.direct_edges)
    context = list(spec.context)
    for cell in spec.cells:
        if cell.role != "row_header":
            continue
        labels = [
            other
            for other in spec.cells
            if other.col == cell.col
            and other.role == "header"
            and other.row < cell.row
        ]
        if not labels:
            continue
        label = max(labels, key=lambda item: item.row)
        direct.append(((label.row, label.col), (cell.row, cell.col), "COLUMN_HEADER_OF"))
        context.append(((cell.row, cell.col), "COLUMN", (label.row, label.col)))
    return replace(
        spec,
        direct_edges=tuple(direct),
        context=tuple(context),
    )


def _spec(kwargs: dict) -> CanonicalFixtureSpec:
    return CanonicalFixtureSpec(**kwargs)


def _two_level_context(values: list[tuple[int, int]], leaf_col_header, top_header, row_header_col=0) -> tuple:
    context = []
    for vr, vc in values:
        context.append(((vr, vc), "COLUMN", leaf_col_header))
        context.append(((vr, vc), "MULTI_LEVEL", top_header))
        context.append(((vr, vc), "ROW", (vr, row_header_col)))
    return tuple(context)


