ROW_HEIGHT = 26.0
CELL_HEIGHT = 18.0
TABLE_TOP = 100.0
DEFAULT_COL_WIDTHS = (150.0, 120.0, 120.0, 120.0, 120.0)


@dataclass(frozen=True)
class CellSpec:
    row: int
    col: int
    text: str
    role: str = "header"  # header | data | row_header | unit | model
    col_span: int = 1


@dataclass(frozen=True)
class CanonicalFixtureSpec:
    fixture_id: str
    scenario: str
    slice_name: str
    cells: tuple[CellSpec, ...]
    # ((header_row, header_col), (value_row, value_col), canonical_relation)
    direct_edges: tuple[tuple[tuple[int, int], tuple[int, int], str], ...] = ()
    # ((value_row, value_col), axis, (header_row, header_col) or None for section)
    context: tuple[tuple[tuple[int, int], str, tuple[int, int] | None], ...] = ()
    # ((value_row, value_col), axis) -> must resolve AMBIGUOUS
    ambiguous: tuple[tuple[tuple[int, int], str], ...] = ()
    section_title: str = ""
    extra_paragraph: str = ""
    continuation: bool = False


def _fixture_id(rc: tuple[int, int]) -> str:
    return f"c{rc[0]}-{rc[1]}"


@dataclass
class FixtureBuild:
    spec: CanonicalFixtureSpec
    page: PageLayout  # flat legacy closure relationships attached
    direct: set[tuple[str, str, str]]
    context: set[tuple[str, str, str]]
    ambiguous: set[tuple[str, str]]
    fixture_digest: str


def _cell_bbox(spec: CanonicalFixtureSpec, cell: CellSpec) -> BBox:
    widths = DEFAULT_COL_WIDTHS
    x0 = 60.0 + sum(widths[: cell.col])
    if cell.col_span > 1:
        x1 = 60.0 + sum(widths[: cell.col + cell.col_span])
    else:
        x1 = x0 + widths[cell.col]
    y0 = TABLE_TOP + cell.row * ROW_HEIGHT
    return BBox(round(x0, 3), round(y0, 3), round(x1, 3), round(y0 + CELL_HEIGHT, 3))


def _grid_cells(spec: CanonicalFixtureSpec) -> dict[tuple[int, int], CellSpec]:
    return {(cell.row, cell.col): cell for cell in spec.cells}


def _legacy_closure(spec: CanonicalFixtureSpec) -> list[tuple[tuple[int, int], tuple[int, int]]]:
    """Simulated legacy annotator: full flat ancestor closure per value.

    For every data cell it emits HEADER_APPLIES_TO edges from (a) the row
    header, (b) every header-zone cell of its column above it (its full
    ancestor chain including unit/model/merged headers).
    """
    grid = _grid_cells(spec)
    data_rows = sorted({cell.row for cell in spec.cells if cell.role in {"data", "row_header"}})
    boundary = min(
        (TABLE_TOP + row * ROW_HEIGHT for row in data_rows),
        default=float("inf"),
    )
    closure: list[tuple[tuple[int, int], tuple[int, int]]] = []
    for cell in spec.cells:
        if cell.role not in {"data", "row_header"}:
            continue
        y0 = TABLE_TOP + cell.row * ROW_HEIGHT
        # column-axis ancestors: header-zone cells above whose horizontal
        # span covers this cell.
        for other in spec.cells:
            if other.role not in {"header", "unit", "model"}:
                continue
            other_y1 = TABLE_TOP + other.row * ROW_HEIGHT + CELL_HEIGHT
            if other_y1 > y0 + 2.0 or other_y1 > boundary + 2.0:
                continue
            if other.col <= cell.col < other.col + other.col_span:
                closure.append(((other.row, other.col), (cell.row, cell.col)))
        # row header: a row_header-role cell in the same row, left of value.
        if cell.role == "data":
            for other in spec.cells:
                if other.role == "row_header" and other.row == cell.row and other.col < cell.col:
                    closure.append(((other.row, other.col), (cell.row, cell.col)))
    return closure


def build_fixture(spec: CanonicalFixtureSpec) -> FixtureBuild:
    fixture_id = spec.fixture_id
    grid = _grid_cells(spec)
    cells: list[TableCell] = []
    blocks: list[LayoutBlock] = []
    row_ids: dict[int, str] = {}
    col_ids: dict[int, str] = {}
    order = 0
    heading_bbox = BBox(60.0, 40.0, 320.0, 60.0)
    blocks.append(
        LayoutBlock(
            block_id=f"{fixture_id}-heading",
            block_type="HEADING",
            bbox=heading_bbox,
            reading_order=order,
            text=spec.section_title or "Technical Specifications",
            page_number=1,
            section_id=f"{fixture_id}-section",
            section_title=spec.section_title or "Technical Specifications",
            parser_name="CANONICAL_FIXTURE",
            parser_version="1",
        )
    )
    order += 1
    if spec.extra_paragraph:
        blocks.append(
            LayoutBlock(
                block_id=f"{fixture_id}-diagram",
                block_type="OTHER",
                bbox=BBox(470.0, 400.0, 530.0, 470.0),
                reading_order=order,
                text=spec.extra_paragraph,
                page_number=1,
                section_id=f"{fixture_id}-section",
                section_title=spec.section_title or "Technical Specifications",
                parser_name="CANONICAL_FIXTURE",
                parser_version="1",
            )
        )
        order += 1
    for rc in sorted(grid):
        cell = grid[rc]
        bbox = _cell_bbox(spec, cell)
        cell_id = f"{fixture_id}-{_fixture_id(rc)}"
        row_ids.setdefault(cell.row, f"{fixture_id}-r{cell.row}")
        if cell.col_span > 1:
            col_key = f"{fixture_id}-col-{cell.col}-{cell.col + cell.col_span - 1}"
        else:
            col_key = f"{fixture_id}-col-{cell.col}"
        col_ids.setdefault(cell.col, col_key)
        cells.append(
            TableCell(
                cell_id=cell_id,
                bbox=bbox,
                text=cell.text,
                page_number=1,
                row_id=row_ids[cell.row],
                column_id=col_key,
            )
        )
        blocks.append(
            LayoutBlock(
                block_id=cell_id,
                block_type="TABLE_CELL",
                bbox=bbox,
                reading_order=order,
                text=cell.text,
                page_number=1,
                section_id=f"{fixture_id}-section",
                section_title=spec.section_title or "Technical Specifications",
                table_region_id=f"{fixture_id}-table",
                row_id=row_ids[cell.row],
                column_id=col_key,
                parser_name="CANONICAL_FIXTURE",
                parser_version="1",
            )
        )
        order += 1

    relationships: list[HeaderRelationship] = []
    for (hr, hc), (vr, vc) in _legacy_closure(spec):
        relationships.append(
            HeaderRelationship(
                relationship_id=f"{fixture_id}-legacy-{len(relationships)}",
                header_block_id=f"{fixture_id}-c{hr}-{hc}",
                value_block_id=f"{fixture_id}-c{vr}-{vc}",
                relationship_type="HEADER_APPLIES_TO",
                page_number=1,
                table_region_id=f"{fixture_id}-table",
            )
        )

    region_cells = tuple(cell.cell_id for cell in cells)
    rows = tuple(
        TableRow(row_id, _union([cell.bbox for cell in cells if cell.row_id == row_id]), 1, tuple(c.cell_id for c in cells if c.row_id == row_id))
        for row_id in sorted(row_ids.values())
    )
    columns = tuple(
        TableColumn(column_id, _union([cell.bbox for cell in cells if cell.column_id == column_id]), 1, tuple(c.cell_id for c in cells if c.column_id == column_id))
        for column_id in sorted({cell.column_id for cell in cells})
    )
    region = TableRegion(
        table_region_id=f"{fixture_id}-table",
        bbox=_union([cell.bbox for cell in cells]),
        page_number=1,
        row_ids=tuple(sorted(row_ids.values())),
        column_ids=tuple(sorted({cell.column_id for cell in cells})),
        cell_ids=region_cells,
    )
    page = PageLayout(
        document_id=f"canonical-{fixture_id}",
        page_number=1,
        width=612.0,
        height=792.0,
        rotation=0,
        coordinate_origin="top-left",
        blocks=tuple(blocks),
        table_regions=(region,),
        rows=rows,
        columns=columns,
        cells=tuple(cells),
        relationships=tuple(relationships),
        parser_name="CANONICAL_FIXTURE",
        parser_version="1",
    )
    direct = {
        (f"{fixture_id}-{_fixture_id(h)}", f"{fixture_id}-{_fixture_id(v)}", relation)
        for h, v, relation in spec.direct_edges
    }
    context: set[tuple[str, str, str]] = set()
    for value_rc, axis, header_rc in spec.context:
        value_id = f"{fixture_id}-{_fixture_id(value_rc)}"
        member = fixture_id if header_rc is None else f"{fixture_id}-{_fixture_id(header_rc)}"
        context.add((axis, member, value_id))
    ambiguous = {(f"{fixture_id}-{_fixture_id(v)}", axis) for v, axis in spec.ambiguous}
    digest_payload = json.dumps(
        {"spec": _spec_to_jsonable(spec), "direct": sorted(direct), "context": sorted(context), "ambiguous": sorted(ambiguous)},
        ensure_ascii=False,
        sort_keys=True,
        separators=(",", ":"),
    )
    digest = hashlib.sha256(digest_payload.encode("utf-8")).hexdigest()
    return FixtureBuild(spec=spec, page=page, direct=direct, context=context, ambiguous=ambiguous, fixture_digest=digest)


def _spec_to_jsonable(spec: CanonicalFixtureSpec) -> dict:
    return {
        "fixture_id": spec.fixture_id,
        "scenario": spec.scenario,
        "slice_name": spec.slice_name,
        "cells": [vars(cell) | {} for cell in spec.cells],
        "direct_edges": [list(edge) for edge in spec.direct_edges],
        "context": [[list(v), axis, list(h) if h else None] for v, axis, h in spec.context],
        "ambiguous": [[list(v), axis] for v, axis in spec.ambiguous],
        "section_title": spec.section_title,
        "extra_paragraph": spec.extra_paragraph,
        "continuation": spec.continuation,
    }


def _union(boxes):
    result = boxes[0]
    for box in boxes[1:]:
        result = result.union(box)
    return result.rounded()


