"""Synthetic canonical contract fixtures (Phase LA-1.1).

Each fixture is a hand-authored micro layout with EXPLICIT human-specified
truth for three layers:

1. ``direct_edges``  - typed DIRECT relations (hand-authored, never
   generated by a closure function).
2. ``context``       - derived context closure per data cell (hand-authored).
3. ``ambiguous``     - axes that must resolve to AMBIGUOUS.

A simulated legacy annotator emits the full flat ancestor closure for
every data cell; contract mapping must recover layer 1 from that flat
set, and context derivation must reproduce layer 2/3.

These fixtures are pure engineering content (no private data).
"""
