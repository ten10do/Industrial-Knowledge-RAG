def canonical_fixtures() -> list[FixtureBuild]:
    return [build_fixture(spec) for spec in FIXTURE_SPECS]


def fixtures_digest() -> str:
    payload = json.dumps(
        [build.fixture_digest for build in canonical_fixtures()],
        sort_keys=True,
        separators=(",", ":"),
    )
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()


def write_fixture_report(path: str | Path) -> dict:
    """Aggregate (non-private) fixture inventory for tracked docs."""
    fixtures = canonical_fixtures()
    report = {
        "status": "CANONICAL_FIXTURES_READY",
        "fixture_count": len(fixtures),
        "digest": fixtures_digest(),
        "scenarios": [
            {"fixture_id": build.spec.fixture_id, "scenario": build.spec.scenario, "slice": build.spec.slice_name}
            for build in fixtures
        ],
        "direct_edge_total": sum(len(build.direct) for build in fixtures),
        "context_edge_total": sum(len(build.context) for build in fixtures),
        "ambiguous_total": sum(len(build.ambiguous) for build in fixtures),
    }
    output = Path(path)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(json.dumps(report, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    return report
